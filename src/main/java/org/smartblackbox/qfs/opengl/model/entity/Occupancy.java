package org.smartblackbox.qfs.opengl.model.entity;

import lombok.Getter;
import lombok.Setter;
import org.ini4j.Wini;
import org.joml.Vector3d;
import org.joml.Vector3i;
import org.smartblackbox.qfs.settings.Project;
import org.smartblackbox.utils.AbstractSettings;
import org.smartblackbox.utils.ISettings;

/**
 * Represents the relationship between an Identity and a Node.
 * <br>
 * <br>
 * An Identity does not directly have a position in REM-FIELD.
 * Instead, it occupies a Node through an Occupancy relation.
 * <br>
 * <br>
 * The Occupancy object is also the location where transport state is stored.
 * This is important because pressure belongs to the relationship:
 * <br>
 *     Identity <-> Node
 * <br>
 * <br>
 * and not to the Identity itself or the Node itself.
 * <br>
 * <br>
 * Example:
 * <br>
 *     Identity A
 *          |
 *          |
 *      Occupancy
 *          |
 *          |
 *       Node(10,5,3)
 * <br>
 * <br>
 * The occupancy can later move to another Node while keeping its accumulated
 * transport state.
 */
@Getter
@Setter
public class Occupancy extends AbstractSettings implements ISettings {

    /**
     * The Identity currently occupying this node.
     * <br><br>
     * Identity contains the oscillator behaviour and is the source/receiver
     * of field interaction.
     */
    private Identity identity = new Identity("");


    /**
     * The lattice node currently occupied by this Identity.
     * <br><br>
     * Node represents the physical location inside the REM-FIELD lattice.
     */
    private Node node;


    /**
     * Accumulated transport pressure.
     * <br><br>
     * Pressure is generated by differences in the surrounding field.
     * <br><br>
     * A nearby Identity creates stronger pressure gain because its wave
     * amplitude is higher.
     * <br><br>
     * Pressure behaves like a stored tendency to move:
     * <br><br>
     *     pressure += localGradient * gain
     * <br><br>
     * When pressure reaches the transfer condition, the occupancy can move
     * to another node.
     * <br><br>
     * Remaining excess pressure is preserved after transfer.
     */
    private double pressure;


    /**
     * Measured local gradient from surrounding nodes.
     * <br><br>
     * The Identity does not know its absolute position or the location of
     * other identities.
     * <br><br>
     * It only measures the six neighboring nodes:
     * <br><br>
     *     LEFT / RIGHT
     *     TOP / BOTTOM
     *     FRONT / BACK
     * <br><br>
     * The gradient gives:
     * <br><br>
     *     - direction of influence
     *     - intensity of influence
     */
    private final Vector3d gradient = new Vector3d();


    /**
     * Direction of the next possible transport.
     * <br><br>
     * This is derived from the gradient.
     * <br><br>
     * Example:
     * <br><br>
     *     gradient.x > 0
     * <br><br>
     * means the occupancy has a tendency to move towards the +X neighbour.
     */
    private final Vector3d transportDirection = new Vector3d();


    /**
     * Creates an empty occupancy.
     * <br><br>
     * The identity and node can be assigned later.
     */
    public Occupancy() {
    }

    @Override
    public AbstractSettings clone() {
        return null;
    }

    @Override
    public void loadFromFile(String filename) {
    }

    @Override
    public void saveToFile(String filename) {
    }

    @Override
    public void loadFromFile(Wini ini, String section, int index) {
        super.loadFromFile(ini, section, index);
        identity.loadFromFile(ini, section, index);
        int x = getInt(section + index, "nodeIndex.x", 0);
        int y = getInt(section + index, "nodeIndex.y", 0);
        int z = getInt(section + index, "nodeIndex.z", 0);
        node = Project.getInstance().scene.getLattice().getNodeByIndex(new Vector3i(x, y, z));
    }

    @Override
    public void saveToFile(Wini ini, String section, int index) {
        super.saveToFile(ini, section, index);
        identity.saveToFile(ini, section, index);
        put(section + index, "nodeIndex.x", node.getIndex().x);
        put(section + index, "nodeIndex.y", node.getIndex().y);
        put(section + index, "nodeIndex.z", node.getIndex().z);
    }

    /**
     * Creates an occupancy relation between an Identity and a Node.
     *
     * @param identity Identity being transported
     * @param node Initial node location
     */
    public Occupancy(Identity identity, Node node) {
        this.identity = identity;
        this.node = node;
    }


    /**
     * Updates the occupied node.
     * <br><br>
     * This method intentionally does not reset pressure.
     * <br><br>
     * The reason:
     * Pressure represents accumulated transport state.
     * When an identity moves, excess pressure continues into the next
     * occupancy location.
     * <br><br>
     * This allows momentum-like behaviour to emerge.
     *
     * @param node new occupied node
     */
    public void moveTo(Node node) {
        this.node = node;
    }


    /**
     * Adds pressure generated by the local field gradient.
     *
     * @param amount pressure contribution
     */
    public void addPressure(double amount) {
        pressure += amount;
    }


    /**
     * Removes consumed pressure while keeping possible excess pressure.
     * <br><br>
     * Example:
     * <br><br>
     * pressure = 1.35
     * <br><br>
     * transfer consumes 1.0
     * <br><br>
     * remaining pressure = 0.35
     */
    public void consumePressure(double amount) {
        pressure -= amount;

        if (pressure < 0) {
            pressure = 0;
        }
    }


    /**
     * Clears temporary measurements.
     * <br><br>
     * This does not remove transport memory.
     * Pressure remains unchanged.
     */
    public void clearGradient() {
        gradient.set(0);
        transportDirection.set(0);
    }
}