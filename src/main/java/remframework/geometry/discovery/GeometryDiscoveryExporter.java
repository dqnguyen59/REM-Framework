package remframework.geometry.discovery;

import org.joml.Vector3i;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

public final class GeometryDiscoveryExporter {
    public static final String GENERATOR_NAME = "REM Framework Geometry Discovery Engine";
    public static final String GENERATOR_VERSION = "0.1";

    public Path export(GeometryDiscoveryResult result, Path requestedPath) throws IOException {
        Path normalized = requestedPath.toAbsolutePath().normalize();
        if (normalized.getFileName() != null
                && normalized.getFileName().toString().equalsIgnoreCase("cubic-lattice.toml"))
            throw new IllegalArgumentException(
                    "Geometry discovery must never overwrite lattice/cubic-lattice.toml.");
        Path target = uniquePath(normalized);
        if (target.getParent() != null) Files.createDirectories(target.getParent());
        Files.writeString(target, serialize(result), StandardCharsets.UTF_8);
        return target;
    }

    public String serialize(GeometryDiscoveryResult result) {
        GeometryDiscoveryModel model = result.model();
        GeometryDiscoverySettings settings = result.settings();
        GeometryDiscoveryMetrics metrics = result.metrics();
        RuntimeCompatibility compatibility = result.runtimeCompatibility();
        StringBuilder out = new StringBuilder("""
                # ==============================================================================
                # REM Framework Candidate Lattice Model
                #
                # This file was generated by the Geometry Discovery Engine.
                #
                # It contains an explicit finite candidate geometry produced by numerical
                # relaxation. It is not part of the built-in System Cubic Lattice.
                #
                # Generated by : REM Framework Geometry Discovery Engine
                # Format       : 1.0
                # ==============================================================================

                """);
        line(out, "name", model.name() + " candidate");
        line(out, "description", model.description());
        line(out, "formatVersion", "1.0");
        line(out, "generator", GENERATOR_NAME);
        line(out, "generatorVersion", GENERATOR_VERSION);
        line(out, "creationTimestamp", Instant.now().toString());
        out.append("generated = true\n");
        out.append("systemTemplate = false\n");
        out.append("runtimeCompatible = ").append(compatibility.compatible()).append('\n');
        line(out, "runtimeCompatibilityReason", compatibility.reason());
        out.append('\n').append("[model]\n");
        line(out, "type", "explicit");
        out.append("dimensionality = 3\n");
        Vector3i dimensions = compatibility.compatible() ? compatibility.dimensions()
                : new Vector3i(model.nodes().size(), 1, 1);
        out.append("dimensions = [").append(dimensions.x).append(", ")
                .append(dimensions.y).append(", ").append(dimensions.z).append("]\n");
        number(out, "equilibriumDistance", settings.targetDistance());
        number(out, "distanceTolerance", settings.convergenceTolerance());
        out.append('\n').append("[discovery]\n");
        number(out, "targetDistance", settings.targetDistance());
        out.append("converged = ").append(metrics.converged()).append('\n');
        out.append("iterations = ").append(metrics.iterationCount()).append('\n');
        out.append('\n').append("[discovery.metrics]\n");
        number(out, "totalEdgeLengthError", metrics.totalEdgeLengthError());
        number(out, "meanConnectedNeighborDistance", metrics.meanConnectedNeighborDistance());
        number(out, "minimumConnectedNeighborDistance", metrics.minimumConnectedNeighborDistance());
        number(out, "maximumConnectedNeighborDistance", metrics.maximumConnectedNeighborDistance());
        number(out, "standardDeviationConnectedNeighborDistance",
                metrics.standardDeviationConnectedNeighborDistance());
        number(out, "minimumDistinctNodeDistance", metrics.minimumDistinctNodeDistance());
        out.append("collisionViolationCount = ").append(metrics.collisionViolationCount()).append('\n');
        out.append("connectedComponentCount = ").append(metrics.connectedComponentCount()).append('\n');
        number(out, "extentX", metrics.extentX());
        number(out, "extentY", metrics.extentY());
        number(out, "extentZ", metrics.extentZ());
        line(out, "effectiveDimensionality", metrics.effectiveDimensionality());

        Map<Integer, List<String>> neighbors = neighbors(model, compatibility);
        int sequentialIndex = 0;
        for (DiscoveryNode node : model.sortedNodes()) {
            Vector3i index = compatibility.compatible()
                    ? compatibility.indices().get(node.id())
                    : new Vector3i(sequentialIndex++, 0, 0);
            out.append('\n').append("[[nodes]]\n");
            line(out, "id", Integer.toString(node.id()));
            out.append("index = [").append(index.x).append(", ").append(index.y)
                    .append(", ").append(index.z).append("]\n");
            out.append("position = [").append(format(node.position().x)).append(", ")
                    .append(format(node.position().y)).append(", ")
                    .append(format(node.position().z)).append("]\n");
            out.append("neighbors = [");
            List<String> nodeNeighbors = neighbors.getOrDefault(node.id(), List.of());
            for (int i = 0; i < nodeNeighbors.size(); i++) {
                if (i > 0) out.append(", ");
                out.append('"').append(nodeNeighbors.get(i)).append('"');
            }
            out.append("]\n");
        }
        return out.toString();
    }

    private Map<Integer, List<String>> neighbors(GeometryDiscoveryModel model,
                                                 RuntimeCompatibility compatibility) {
        if (compatibility.compatible()) return directionalNeighbors(model, compatibility);
        Map<Integer, List<String>> result = new HashMap<>();
        for (DiscoveryNode node : model.nodes()) result.put(node.id(), new ArrayList<>());
        for (DiscoveryConnection connection : model.connections()) {
            result.get(connection.firstNodeId()).add(Integer.toString(connection.secondNodeId()));
            result.get(connection.secondNodeId()).add(Integer.toString(connection.firstNodeId()));
        }
        result.values().forEach(list -> list.sort(
                Comparator.comparingInt(Integer::parseInt)));
        return result;
    }

    private Map<Integer, List<String>> directionalNeighbors(
            GeometryDiscoveryModel model, RuntimeCompatibility compatibility) {
        Map<Vector3i, Integer> idByIndex = new HashMap<>();
        compatibility.indices().forEach(
                (id, index) -> idByIndex.put(new Vector3i(index), id));
        int[][] offsets = {{1, 0, 0}, {0, 1, 0}, {0, 0, 1},
                {-1, 0, 0}, {0, -1, 0}, {0, 0, -1}};
        Map<Integer, List<String>> result = new HashMap<>();
        for (DiscoveryNode node : model.nodes()) {
            Vector3i index = compatibility.indices().get(node.id());
            List<String> slots = new ArrayList<>(6);
            for (int[] offset : offsets) {
                Integer neighbor = idByIndex.get(new Vector3i(index).add(
                        offset[0], offset[1], offset[2]));
                slots.add(neighbor == null ? "" : Integer.toString(neighbor));
            }
            result.put(node.id(), slots);
        }
        return result;
    }

    private Path uniquePath(Path requested) {
        if (Files.notExists(requested)) return requested;
        String filename = requested.getFileName().toString();
        int dot = filename.toLowerCase(Locale.ROOT).endsWith(".toml")
                ? filename.length() - 5 : filename.length();
        String base = filename.substring(0, dot);
        String extension = filename.substring(dot);
        for (int suffix = 2; ; suffix++) {
            Path candidate = requested.resolveSibling(base + "-" + suffix + extension);
            if (Files.notExists(candidate)) return candidate;
        }
    }

    private void line(StringBuilder out, String key, String value) {
        out.append(key).append(" = \"").append(escape(value)).append("\"\n");
    }

    private void number(StringBuilder out, String key, double value) {
        out.append(key).append(" = ").append(format(value)).append('\n');
    }

    private String format(double value) {
        if (!Double.isFinite(value))
            throw new IllegalArgumentException("Cannot export a non-finite number.");
        return String.format(Locale.ROOT, "%.17g", value)
                .replaceFirst("e([+-])0+([0-9])", "e$1$2");
    }

    private String escape(String value) {
        return value.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\n", "\\n").replace("\r", "\\r");
    }
}
